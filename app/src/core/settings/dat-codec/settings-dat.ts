// settings.dat of the Editor/Assembler (editor-ui §11.4; ARCHITECTURE.md 3.10, 5.6). Owner: E4.
//
// The file: 57 lines, CR LF, each `<value>$<name>`, always in the same order. The reader is the
// original's TOptions::LoadSettings (optionsS.cpp:228-912) operation by operation (c-reader.ts):
// line N is accepted only if the text from its `$` on is the expected name, so a missing or extra
// line puts every later setting back to its default ("positional"). The writer is
// TOptions::SaveSettings (optionsS.cpp:134-221) with the v5.16.01 header.
//
// What the port does not have (1.4 note 21): the four window lines ($main top/left/height/width)
// and `$maximized edit` are read and ignored, and written with the original's defaults.

import { TabType, type Bytes, type EditorSettings, type SyntaxElement, type SyntaxStyle } from '../../../contracts';
import { encode } from '../../codec/cp1252';
import { COLOR1_STYLES, COLOR_PRESET } from '../../highlight';
import { DEFAULT_EDITOR_SETTINGS } from '../defaults';
import { DatReader, atoi, cText } from './c-reader';

/** Line 1 as v5.16.1 writes it (`"$Settings for " << TITLE << "  DO NOT EDIT THIS FILE!!!!"`). */
export const SETTINGS_DAT_HEADER = '$Settings for EASy68K Editor/Assembler v5.16.01  DO NOT EDIT THIS FILE!!!!';

/** Number of lines of the file, the header included. */
export const SETTINGS_DAT_LINES = 57;

/**
 * Lines 14 and 18-21 on export (1.4 note 21). `$maximized edit` 0 and `$main top` / `$main left`
 * are the original's defaults (editor-ui §11.4). Its default height and width are two thirds of the
 * screen, which a web page cannot give for a Windows screen; the shipped file's 943 and 925 are used.
 */
export const SETTINGS_DAT_WINDOW = Object.freeze({ maximized: 0, top: 106, left: 513, height: 943, width: 925 });

/** The style blocks of lines 22-53, in file order, with the name each line carries. */
export const STYLE_BLOCKS: readonly (readonly [SyntaxElement, string])[] = [
  ['code', 'code'],
  ['unknown', 'unknown'],
  ['directive', 'directive'],
  ['comment', 'comment'],
  ['label', 'label'],
  ['structure', 'structure'],
  ['error', 'error'],
  ['text', 'text'],
];

/**
 * The settings settings.dat holds, i.e. every key of EditorSettings except the port's own
 * (`template` is template.NEW; `lineNumbers` is new).
 */
export type DatEditorSettings = Omit<EditorSettings, 'template' | 'lineNumbers'>;

/** The keys of DatEditorSettings, in file order. */
export const SETTINGS_DAT_KEYS: readonly (keyof DatEditorSettings)[] = [
  'generateList',
  'generateSRecord',
  'saveThenAssemble',
  'showWarnings',
  'crossReference',
  'macrosExpanded',
  'structuredExpanded',
  'constantsExpanded',
  'fontName',
  'fontSize',
  'tabType',
  'fixedTabSize',
  'autoIndent',
  'realTabs',
  'assembleBitField',
  'styles',
  'highlightDisabled',
  'printBlack',
  'backgroundColor',
  'colorPreset',
];

/**
 * The values the original starts from before it reads the file, which a line that is missing or
 * out of step leaves in place (`defaultSettings()` and the design-time controls, optionsS.cpp:915-980,
 * optionsS.dfm, editorOptions.dfm): the column "Default when the file is missing" of editor-ui
 * §11.4. They equal the port's defaults except `colorPreset`, whose original default is -1 (none
 * selected; the port's own default is Auto).
 */
export const SETTINGS_DAT_DEFAULTS: Readonly<DatEditorSettings> = Object.freeze({
  ...pickDat(DEFAULT_EDITOR_SETTINGS),
  colorPreset: COLOR_PRESET.none,
});

function pickDat(settings: Readonly<EditorSettings>): DatEditorSettings {
  const { template: _template, lineNumbers: _lineNumbers, ...rest } = settings;
  return structuredClone(rest) as DatEditorSettings;
}

/** `FixedTabSize->Value = atoi(temp)`: the spin box clamps to its MinValue..MaxValue (4..20). */
export function clampTabSize(value: number): number {
  return Math.min(20, Math.max(4, value));
}

/**
 * `cbSize->Text = temp`. The port keeps the size as a number: a text that is a whole number above
 * zero (blanks around it allowed) is taken; anything else is treated as a line that did not match,
 * because the original would fail on it later (`StrToInt(cbSize->Text)` raises on the next New).
 */
function fontSizeOf(text: string): number | null {
  const match = /^\s*\+?(\d{1,4})\s*$/.exec(text);
  if (!match) return null;
  const size = Number(match[1]);
  return size > 0 ? size : null;
}

/** `SyntaxCombo->ItemIndex = atoi(temp)`: an index outside the five items leaves none selected. */
function presetOf(value: number): DatEditorSettings['colorPreset'] {
  return value >= 0 && value <= 4 ? (value as DatEditorSettings['colorPreset']) : COLOR_PRESET.none;
}

/**
 * Reads settings.dat as the original does (editor-ui §11.4, positional rule). The result holds the
 * settings whose line matched; `styles`, which spans 32 lines, is present when at least one of
 * them matched, with the original's default for each style line that did not.
 */
export function parseSettingsDat(bytes: Bytes): Partial<EditorSettings> {
  const file = new DatReader(bytes);
  const result: Partial<DatEditorSettings> = {};
  const flag = (name: string, key: keyof DatEditorSettings) => {
    file.next();
    if (file.isFlagLine(name)) (result as Record<string, unknown>)[key] = file.buffer[0] === 0x31;
  };
  /** A value line whose name matched, or null; the line is consumed either way. */
  const value = (name: string): Uint8Array | null => {
    file.next();
    return file.valueOf(name);
  };

  file.next(); // the header: read and ignored, its version is not checked
  flag('generate list', 'generateList');
  flag('generate s-record', 'generateSRecord');
  flag('save then assemble', 'saveThenAssemble');
  flag('show warnings', 'showWarnings');
  flag('cross reference', 'crossReference');
  flag('macros expanded', 'macrosExpanded');
  flag('structured expand', 'structuredExpanded');
  flag('constants expand', 'constantsExpanded');

  const fontName = value('font name');
  if (fontName) result.fontName = cText(fontName);
  const fontSize = value('font size');
  if (fontSize) {
    const size = fontSizeOf(cText(fontSize));
    if (size !== null) result.fontSize = size;
  }
  file.next();
  if (file.isFlagLine('tab type')) result.tabType = file.buffer[0] === 0x30 ? TabType.Assembly : TabType.Fixed;
  const tabSize = value('fixed tab size');
  if (tabSize) result.fixedTabSize = clampTabSize(atoi(tabSize));

  file.next(); // $maximized edit: no meaning in a tabbed window (1.4 note 21)
  flag('auto indent', 'autoIndent');
  flag('real tabs', 'realTabs');
  flag('assemble bit field', 'assembleBitField');
  for (const name of ['main top', 'main left', 'main height', 'main width']) value(name); // note 21

  const styles = structuredClone(SETTINGS_DAT_DEFAULTS.styles) as Record<SyntaxElement, SyntaxStyle>;
  let anyStyle = false;
  for (const [element, name] of STYLE_BLOCKS) {
    const color = value(`${name} color`);
    if (color) styles[element].color = atoi(color);
    // `bold`, `italic` and `underline` are value lines read with atoi: any non-zero number is on.
    const bold = value(`${name} bold`);
    if (bold) styles[element].bold = atoi(bold) !== 0;
    const italic = value(`${name} italic`);
    if (italic) styles[element].italic = atoi(italic) !== 0;
    const underline = value(`${name} underline`);
    if (underline) styles[element].underline = atoi(underline) !== 0;
    anyStyle ||= color !== null || bold !== null || italic !== null || underline !== null;
  }
  if (anyStyle) result.styles = styles;

  const disabled = value('highlight disabled');
  if (disabled) result.highlightDisabled = atoi(disabled) !== 0;
  flag('print w/black', 'printBlack');
  const background = value('background color');
  if (background) result.backgroundColor = atoi(background);
  const preset = value('color presets');
  if (preset) result.colorPreset = presetOf(atoi(preset));
  return result;
}

/**
 * What an import of settings.dat sets (ARCHITECTURE.md 3.10: "a missing line puts all later lines
 * back to defaults"): every setting the file holds, from its line where that line matched and from
 * SETTINGS_DAT_DEFAULTS otherwise. The port's own settings (`template`, `lineNumbers`) are not
 * part of it.
 */
export function editorSettingsFromDat(bytes: Bytes): DatEditorSettings {
  return { ...structuredClone(SETTINGS_DAT_DEFAULTS), ...parseSettingsDat(bytes) } as DatEditorSettings;
}

const bit = (on: boolean) => (on ? '1' : '0');

/**
 * Writes settings.dat as v5.16.1 does (TOptions::SaveSettings): 57 lines, CR LF, Windows-1252.
 * The `Auto` preset of the port, which the original does not have, is written as -1 (none
 * selected) with the Color1 values (ARCHITECTURE.md 3.10), so the original shows what Auto shows in
 * the light theme. Window lines: SETTINGS_DAT_WINDOW.
 */
export function writeSettingsDat(settings: EditorSettings): Bytes {
  const auto = settings.colorPreset === COLOR_PRESET.auto;
  const styles = auto ? COLOR1_STYLES : settings.styles;
  const preset = auto ? COLOR_PRESET.none : settings.colorPreset;
  const lines: string[] = [
    SETTINGS_DAT_HEADER,
    `${bit(settings.generateList)}$generate list`,
    `${bit(settings.generateSRecord)}$generate s-record`,
    `${bit(settings.saveThenAssemble)}$save then assemble`,
    `${bit(settings.showWarnings)}$show warnings`,
    `${bit(settings.crossReference)}$cross reference`,
    `${bit(settings.macrosExpanded)}$macros expanded`,
    `${bit(settings.structuredExpanded)}$structured expand`,
    `${bit(settings.constantsExpanded)}$constants expand`,
    `${settings.fontName}$font name`,
    `${settings.fontSize}$font size`,
    `${settings.tabType === TabType.Assembly ? 0 : 1}$tab type`,
    `${settings.fixedTabSize}$fixed tab size`,
    `${SETTINGS_DAT_WINDOW.maximized}$maximized edit`,
    `${bit(settings.autoIndent)}$auto indent`,
    `${bit(settings.realTabs)}$real tabs`,
    `${bit(settings.assembleBitField)}$assemble bit field`,
    `${SETTINGS_DAT_WINDOW.top}$main top`,
    `${SETTINGS_DAT_WINDOW.left}$main left`,
    `${SETTINGS_DAT_WINDOW.height}$main height`,
    `${SETTINGS_DAT_WINDOW.width}$main width`,
  ];
  for (const [element, name] of STYLE_BLOCKS) {
    const style = styles[element];
    lines.push(
      `${style.color | 0}$${name} color`,
      `${bit(style.bold)}$${name} bold`,
      `${bit(style.italic)}$${name} italic`,
      `${bit(style.underline)}$${name} underline`,
    );
  }
  lines.push(
    `${bit(settings.highlightDisabled)}$highlight disabled`,
    `${bit(settings.printBlack)}$print w/black`,
    `${settings.backgroundColor | 0}$background color`,
    `${preset}$color presets`,
  );
  return encode(lines.map((line) => `${line}\r\n`).join('')).bytes;
}
