// sim68K.dat of the Simulator (sim-ui §14.3; ARCHITECTURE.md 3.10, 5.6). Owner: E4.
//
// The file: 37 lines, CR LF, each `<value>$<name>`, positional like settings.dat. Lines 2, 3 and
// 34 hold one RAW byte instead of digits: `ElogFlag`, `OlogFlag` and `FullScreenMonitor` are
// `char`s streamed as characters (the shipped file has NUL bytes there). The reader is
// TForm1::LoadSettings (SIM68Ku.cpp:1551-2034) operation by operation (c-reader.ts); the writer is
// TForm1::SaveSettings (SIM68Ku.cpp:1430-1485) with the v5.16.1 header.
//
// What the port does not have (1.4 notes 21 and 29): every window position and size, the I/O
// window's visibility (always visible) and the full-screen monitor are read and ignored, and
// written with the original's defaults (def.h:252-262, SIM68Ku.dfm, defaultSettings()).

import type { Bytes, SimSettings } from '../../../contracts';
import { encode } from '../../codec/cp1252';
import { DEFAULT_SIM_SETTINGS } from '../defaults';
import { DatReader, atoi, cText } from './c-reader';

/** Line 1 as v5.16.1 writes it (TITLE of def.h:23). */
export const SIM68K_DAT_HEADER = '$Settings for EASy68K Simulator v5.16.1  DO NOT EDIT THIS FILE!!!!';

/** Number of lines of the file, the header included. */
export const SIM68K_DAT_LINES = 37;

/**
 * The window lines on export: def.h:252-262 (FORM1_TOP .. HARDWARE_FORM_LEFT), the main window's
 * design-time size (SIM68Ku.dfm: Width 744, Height 500; its position is the system's choice,
 * poDefault, so FORM1_TOP / FORM1_LEFT are written), `simIO visible` 1 (it is always visible) and
 * the full-screen monitor byte 0 (initSim() resets it on every load, sim-ui §14.1).
 */
export const SIM68K_DAT_WINDOWS = Object.freeze({
  mainTop: 100,
  mainLeft: 100,
  mainHeight: 500,
  mainWidth: 744,
  simIOTop: 300,
  simIOLeft: 200,
  simIOVisible: 1,
  memoryTop: 80,
  memoryLeft: 280,
  stackTop: 200,
  stackLeft: 40,
  stackHeight: 538,
  hardwareTop: 100,
  hardwareLeft: 240,
  fullScreenMonitor: 0,
});

/** The panels whose visibility the file holds (lines 15, 20, 27), by panel id (2.4). */
export const SIM68K_DAT_PANELS = ['memory', 'stack', 'hardware'] as const;
export type Sim68KPanel = (typeof SIM68K_DAT_PANELS)[number];

/** The settings sim68K.dat holds: every key of SimSettings except the port's own. */
export type DatSimSettings = Omit<SimSettings, 'speed' | 'highlightChangedRegisters'>;

/** What the original starts from before it reads the file (sim-ui §14.3 "Default"). */
export const SIM68K_DAT_DEFAULTS: Readonly<DatSimSettings> = Object.freeze(pickDat(DEFAULT_SIM_SETTINGS));

function pickDat(settings: Readonly<SimSettings>): DatSimSettings {
  const { speed: _speed, highlightChangedRegisters: _highlight, ...rest } = settings;
  return structuredClone(rest) as DatSimSettings;
}

/**
 * The text of an address field (`MemoryFrm->Address1->Text = temp`, the Hardware fields alike): a
 * TMaskEdit with the mask `aaaaaa` (six characters). The port keeps the address as a number: one
 * to six hexadecimal digits, blanks around them allowed, are taken; anything else is treated as a
 * line that did not match.
 */
function addressOf(text: string): number | null {
  const match = /^\s*([0-9A-Fa-f]{1,6})\s*$/.exec(text);
  return match ? Number.parseInt(match[1] as string, 16) : null;
}

/** `Font->Size = atoi(temp)`: the port takes a size above zero; anything else did not match. */
function fontSizeOf(value: number): number | null {
  return value > 0 ? value : null;
}

/** `UpDown1->Position = atoi(temp)`: the up/down control keeps its position within 10..1000. */
export function clampAutoTraceInterval(value: number): number {
  return Math.min(1000, Math.max(10, value));
}

/** Result of parseSim68KDat: the settings whose line matched, and the panel lines that matched. */
export type ParsedSim68KDat = Partial<SimSettings> & { panels: Record<string, boolean> };

/**
 * Reads sim68K.dat as the original does (sim-ui §14.3, positional rule). The result holds the
 * settings whose line matched (a font is present when its name or its size matched, with the
 * default for the other) and, in `panels`, the visibility lines that matched (`'1'` = shown).
 */
export function parseSim68KDat(bytes: Bytes): ParsedSim68KDat {
  const file = new DatReader(bytes);
  const result: Partial<DatSimSettings> = {};
  const panels: Record<string, boolean> = {};
  const value = (name: string, limit: 'size' | 'strlen' = 'size'): Uint8Array | null => {
    file.next();
    return file.valueOf(name, limit);
  };
  const flag = (name: string): boolean | null => {
    file.next();
    return file.isFlagLine(name) ? file.buffer[0] === 0x31 : null;
  };

  file.next(); // the header: ignored
  file.next();
  if (file.isFlagLine('exec log')) {
    const raw = file.firstChar(); // `buffer[0] >= 0 && buffer[0] <= 3`: a raw byte, not a digit
    if (raw >= 0 && raw <= 3) result.execLogType = raw as DatSimSettings['execLogType'];
  }
  file.next();
  if (file.isFlagLine('output log')) {
    const raw = file.firstChar();
    if (raw >= 0 && raw <= 1) result.outputLogType = raw as DatSimSettings['outputLogType'];
  }
  const exceptions = flag('exceptions');
  if (exceptions !== null) result.exceptions = exceptions;
  for (const name of ['main top', 'main left', 'main height', 'main width', 'simIO top', 'simIO left']) value(name);
  flag('simIO visible'); // the I/O window is always visible at start-up (sim-ui §14.3, line 11)
  value('memory top');
  value('memory left');
  const memory = value('memory address', 'strlen');
  if (memory) {
    const address = addressOf(cText(memory));
    if (address !== null) result.memoryAddress = address;
  }
  const memoryVisible = flag('memory visible');
  if (memoryVisible !== null) panels.memory = memoryVisible;
  value('stack top');
  value('stack left');
  value('stack height');
  const which = value('which stack');
  if (which) {
    // `whichStack->ItemIndex = atoi(temp)`: an index outside the nine items selects none; the port
    // keeps its default then.
    const index = atoi(which);
    if (index >= 0 && index <= 8) result.whichStack = index;
  }
  const stackVisible = flag('stack visible');
  if (stackVisible !== null) panels.stack = stackVisible;
  value('hardware top');
  value('hardware left');
  const addresses: [string, 'seg7Address' | 'ledAddress' | 'switchAddress' | 'buttonAddress'][] = [
    ['7-segment address', 'seg7Address'],
    ['LED address', 'ledAddress'],
    ['switch address', 'switchAddress'],
    ['button address', 'buttonAddress'],
  ];
  for (const [name, key] of addresses) {
    const text = value(name, 'strlen');
    if (!text) continue;
    const address = addressOf(cText(text));
    if (address !== null) result[key] = address;
  }
  const hardwareVisible = flag('hardware visible');
  if (hardwareVisible !== null) panels.hardware = hardwareVisible;

  const fonts: [string, 'outputFont' | 'listingFont' | 'printerFont'][] = [
    ['output', 'outputFont'],
    ['listing', 'listingFont'],
    ['printer', 'printerFont'],
  ];
  for (const [name, key] of fonts) {
    const fontName = value(`${name} font name`, 'strlen');
    const fontSize = value(`${name} font size`, 'strlen');
    const size = fontSize ? fontSizeOf(atoi(fontSize)) : null;
    if (fontName === null && size === null) continue;
    result[key] = {
      name: fontName ? cText(fontName) : SIM68K_DAT_DEFAULTS[key].name,
      size: size ?? SIM68K_DAT_DEFAULTS[key].size,
    };
  }
  // Line 34: a raw byte the original never reads back successfully (sim-ui §14.3); the port has
  // only monitor 1 anyway (1.4 note 29).
  value('fullscreen monitor', 'strlen');
  const bitField = flag('bit field enabled');
  if (bitField !== null) result.bitField = bitField;
  const interval = value('auto trace interval', 'strlen');
  if (interval) result.autoTraceIntervalMs = clampAutoTraceInterval(atoi(interval));
  const disable = flag('disable display');
  if (disable !== null) result.disableDisplay = disable;
  return { ...result, panels };
}

/** What an import of sim68K.dat sets (positional rule, 3.10): the settings and the three panels. */
export interface ImportedSim68KDat {
  settings: DatSimSettings;
  /** Every panel of SIM68K_DAT_PANELS: shown when its line matched with `1`, otherwise hidden. */
  panels: Record<Sim68KPanel, boolean>;
}

/** Every setting the file holds, from its line where it matched and from the defaults otherwise. */
export function simSettingsFromDat(bytes: Bytes): ImportedSim68KDat {
  const { panels, ...parsed } = parseSim68KDat(bytes);
  return {
    settings: { ...structuredClone(SIM68K_DAT_DEFAULTS), ...parsed } as DatSimSettings,
    panels: {
      memory: panels.memory === true,
      stack: panels.stack === true,
      hardware: panels.hardware === true,
    },
  };
}

const bit = (on: boolean) => (on ? '1' : '0');
const hex6 = (value: number) => (value & 0xffffff).toString(16).toUpperCase().padStart(6, '0');

/**
 * Writes sim68K.dat as v5.16.1 does (TForm1::SaveSettings): 37 lines, CR LF, Windows-1252, with
 * raw bytes on lines 2, 3 and 34. `panels` gives the visibility of `memory`, `stack` and
 * `hardware` (a missing key is hidden). Window lines: SIM68K_DAT_WINDOWS.
 */
export function writeSim68KDat(settings: SimSettings, panels: Record<string, boolean>): Bytes {
  const w = SIM68K_DAT_WINDOWS;
  const visible = (id: Sim68KPanel) => bit(panels[id] === true);
  // A line is its value (text, or one raw byte) and its name.
  const lines: [string | number, string][] = [
    [settings.execLogType, 'exec log'],
    [settings.outputLogType, 'output log'],
    [bit(settings.exceptions), 'exceptions'],
    [String(w.mainTop), 'main top'],
    [String(w.mainLeft), 'main left'],
    [String(w.mainHeight), 'main height'],
    [String(w.mainWidth), 'main width'],
    [String(w.simIOTop), 'simIO top'],
    [String(w.simIOLeft), 'simIO left'],
    [String(w.simIOVisible), 'simIO visible'],
    [String(w.memoryTop), 'memory top'],
    [String(w.memoryLeft), 'memory left'],
    [hex6(settings.memoryAddress), 'memory address'],
    [visible('memory'), 'memory visible'],
    [String(w.stackTop), 'stack top'],
    [String(w.stackLeft), 'stack left'],
    [String(w.stackHeight), 'stack height'],
    [String(settings.whichStack), 'which stack'],
    [visible('stack'), 'stack visible'],
    [String(w.hardwareTop), 'hardware top'],
    [String(w.hardwareLeft), 'hardware left'],
    [hex6(settings.seg7Address), '7-segment address'],
    [hex6(settings.ledAddress), 'LED address'],
    [hex6(settings.switchAddress), 'switch address'],
    [hex6(settings.buttonAddress), 'button address'],
    [visible('hardware'), 'hardware visible'],
    [settings.outputFont.name, 'output font name'],
    [String(settings.outputFont.size), 'output font size'],
    [settings.listingFont.name, 'listing font name'],
    [String(settings.listingFont.size), 'listing font size'],
    [settings.printerFont.name, 'printer font name'],
    [String(settings.printerFont.size), 'printer font size'],
    [w.fullScreenMonitor, 'fullscreen monitor'],
    [bit(settings.bitField), 'bit field enabled'],
    [String(settings.autoTraceIntervalMs), 'auto trace interval'],
    [bit(settings.disableDisplay), 'disable display'],
  ];
  const parts: Uint8Array[] = [encode(`${SIM68K_DAT_HEADER}\r\n`).bytes];
  for (const [lineValue, name] of lines) {
    if (typeof lineValue === 'number') parts.push(Uint8Array.of(lineValue & 0xff));
    parts.push(encode(`${typeof lineValue === 'number' ? '' : lineValue}$${name}\r\n`).bytes);
  }
  const out = new Uint8Array(parts.reduce((total, part) => total + part.length, 0));
  let offset = 0;
  for (const part of parts) {
    out.set(part, offset);
    offset += part.length;
  }
  return out;
}
