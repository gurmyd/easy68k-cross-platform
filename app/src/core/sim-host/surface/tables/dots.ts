// The round dots of wide pens (ARCHITECTURE.md 3.4 rule 4; trap15-b §6.2): what GDI draws at one
// point when the pen is 2 or more pixels wide.
//
//   penDot(width)         a zero-length line (tasks 84, 85) and a one-point ellipse (tasks 88, 91)
//   rectangleDot(width)   a one-point rectangle (tasks 87, 90; trap15-b §6.3 case C)
//
// The two are the same dot except at fifteen pen widths, where the rectangle lacks one pixel of a
// row near the top and, at eleven of them, one pixel of a row near the bottom.
//
// EVERY DOT IS MEASURED, the pen widths 2-255, on Windows GDI with the calls the original makes
// (`Rectangle(x, y, x + 1, y + 1)`, `MoveToEx` + `LineTo`, `Ellipse(x, y, x + 1, y + 1)`, the pen
// from `CreatePenIndirect`). GDI does not draw a circle: it fills a polygon it makes of the pen, and
// the result follows no rule short enough to write down. From width 16 on it differs from the
// pixels inside the circle of that diameter at most widths, and at 35 widths it is not even
// symmetric. Hence a table.
//
// Shape of a dot. A pen of width w gives a dot of 2k + 1 rows, k = floor((w - 1) / 2), centred on
// its point; the centre row covers x - k .. x + k. So the widths 2k + 1 and 2k + 2 give dots of one
// size, though not always of one shape. Every row is one unbroken run.
//
// How the table stores it:
//
//   NARROWING[w - 2]   one character per row above the centre row, from the centre outwards: by
//                      how many pixels that row's half-width is smaller than the half-width of
//                      the row before it, as a digit of base 36. Width 9, `0102`, is the
//                      half-widths 4 (centre), 4, 3, 3, 1:
//
//                           ...###...
//                           .#######.
//                           .#######.
//                           #########
//                           #########    <- centre row, half-width 4
//                           #########
//                           .#######.
//                           .#######.
//                           ...###...
//
//                      The rows below the centre mirror those above, and each row is centred.
//   LOPSIDED_ROWS[w]   the rows of the pen's dot that are NOT what that mirroring gives, each as
//                      `row:first..last`: the row relative to the centre row, then its first and
//                      its last pixel relative to x.
//   RECTANGLE_ROWS[w]  the rows in which the one-point rectangle differs from the pen's dot.
//
// Where the numbers come from, and how to measure them again: the capture program of
// tests/oracle/gdi-capture (owner T2), given for each width 2-255 the cases `width w` and
// `rect 150 150 150 150`, `line 150 150 150 150` or `ellipse 150 150 150 150` on a 300 x 300
// canvas. Captured on Windows 11 (10.0.26300) on 2026-11-21, at gate I1. The same dots came out at
// other positions, for the unfilled calls, for `lineTo`, and in a drawing mode other than Copy
// (every pixel combined once). The widths 2-9 are also the figure of trap15-b §6.2, and the widths
// 2-14 are in the committed references (tests/conformance/gdi: suites `rects`, `widelines`,
// `modes`). The widths 15-255 are not in the committed references yet
// (docs/requests/SH1-gdi-dots.md); until they are, the test next to this file holds the table to a
// checksum of the capture.
//
// First version by SH1 for the rectangle rule (case C) and the wide-line stub. SH2 owns this file
// from wave 2 on; whether the round caps of wide lines are parts of `penDot` is for SH2 to measure.
//
// Owner: SH1 > SH2.

/** A dot as the pixels it covers around its point (x, y). */
export interface Dot {
  /** The dot covers the rows y - reach .. y + reach. */
  readonly reach: number;
  /** Row y - reach + i covers the pixels x + left[i] .. x + right[i]. */
  readonly left: readonly number[];
  readonly right: readonly number[];
}

