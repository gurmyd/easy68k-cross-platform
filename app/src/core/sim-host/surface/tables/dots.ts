const penDots = new Map<number, Dot>();
const rectangleDots = new Map<number, Dot>();

/** The table's entry for a pen width: a width outside 2-255 counts as the nearest of them. */
function tableWidth(width: number): number {
  return Math.min(Math.max(Math.trunc(width) || 0, MIN_DOT_WIDTH), MAX_DOT_WIDTH);
}

/** A copy of `dot` with the rows listed in `rows` (`row:first..last`, separated by spaces) replaced. */
function withRows(dot: Dot, rows: string | undefined): Dot {
  if (!rows) return dot;
  const left = dot.left.slice();
  const right = dot.right.slice();
  for (const row of rows.split(' ')) {
    const [dy, first, last] = row.split(/:|\.\./).map(Number) as [number, number, number];
    left[dot.reach + dy] = first;
    right[dot.reach + dy] = last;
  }
  return { reach: dot.reach, left, right };
}

/** Decodes NARROWING and LOPSIDED_ROWS for one pen width. */
function decodePenDot(width: number): Dot {
  const narrowing = NARROWING[width - MIN_DOT_WIDTH] as string;
  const reach = narrowing.length;
  const left = new Array<number>(2 * reach + 1);
  const right = new Array<number>(2 * reach + 1);
  let half = reach;
  left[reach] = -half;
  right[reach] = half;
  for (let i = 1; i <= reach; i++) {
    half -= parseInt(narrowing.charAt(i - 1), 36);
    left[reach - i] = left[reach + i] = -half;
    right[reach - i] = right[reach + i] = half;
  }
  return withRows({ reach, left, right }, LOPSIDED_ROWS[width]);
}

/**
 * The dot of a pen `width` pixels wide (2-255): what a zero-length line and a one-point ellipse
 * draw.
 */
export function penDot(width: number): Dot {
  const w = tableWidth(width);
  let dot = penDots.get(w);
  if (!dot) {
    dot = decodePenDot(w);
    penDots.set(w, dot);
  }
  return dot;
}

/** What a one-point rectangle draws with a pen `width` pixels wide (2-255). */
export function rectangleDot(width: number): Dot {
  const w = tableWidth(width);
  let dot = rectangleDots.get(w);
  if (!dot) {
    dot = withRows(penDot(w), RECTANGLE_ROWS[w]);
    rectangleDots.set(w, dot);
  }
  return dot;
}
