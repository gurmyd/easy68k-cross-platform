// ---- bit fields (needs the bit-field option: /b) ----
const BF = ['BFTST', 'BFEXTU', 'BFEXTS', 'BFFFO', 'BFCHG', 'BFCLR', 'BFSET', 'BFINS'];
add(
  'bitfield-reg',
  GROUP('BIT_FIELD on a data register: all eight operations, static and dynamic offset and width'),
  (c) =>
    repeat(48, (i) => {
      const op = BF[i % 8];
      const dyn = Math.floor(i / 8) % 2 === 1;
      const off = dyn ? 'D2' : String(c.int(32));
      const width = dyn ? 'D3' : String(1 + c.int(32));
      const operand = `D0{${off}:${width}}`;
      const body =
        op === 'BFINS'
          ? `BFINS   D1,${operand}`
          : ['BFEXTU', 'BFEXTS', 'BFFFO'].includes(op)
            ? `${op}  ${operand},D1`
            : `${op}   ${operand}`;
      return caseLines(c, {
        body: [body],
        extra: [`    MOVE.L  #${c.int(70) - 3},D2`, `    MOVE.L  #${c.int(40)},D3`],
      });
    }),
  { switches: '/b' },
);
add(
  'bitfield-mem',
  GROUP('BIT_FIELD on memory: offsets reaching into the fifth byte (writes bf1 there: quirk)'),
  (c) =>
    repeat(48, (i) => {
      const op = BF[i % 8];
      const off = String(c.int(32));
      const width = String(1 + c.int(32));
      const operand = `(A0){${off}:${width}}`;
      const body =
        op === 'BFINS'
          ? `BFINS   D1,${operand}`
          : ['BFEXTU', 'BFEXTS', 'BFFFO'].includes(op)
            ? `${op}  ${operand},D1`
            : `${op}   ${operand}`;
      return caseLines(c, { body: [body], memory: true });
    }),
  { switches: '/b' },
);

// ---- write or check ----

const check = process.argv.includes('--check');
let differing = 0;
const names = new Set(programs.map((p) => `${p.name}.X68`));
for (const p of programs) {
  const path = join(OUT, `${p.name}.X68`);
  let old = null;
  try {
    old = readFileSync(path, 'latin1');
  } catch {
    // a new program
  }
  if (old === p.text) continue;
  differing += 1;
  if (check) console.error(`differs: instructions/${p.name}.X68`);
  else writeFileSync(path, p.text, 'latin1');
}
for (const file of readdirSync(OUT).filter((f) => f.startsWith(PREFIX) && f.endsWith('.X68') && !names.has(f))) {
  differing += 1;
  console.error(`${check ? 'stale' : 'remove by hand'}: instructions/${file}`);
}
console.log(`${programs.length} generated programs, ${differing} ${check ? 'differ' : 'written'}`);
process.exit(check && differing > 0 ? 1 : 0);
