/** mulberry32: a small, well-known 32-bit generator; the seed is the program name. */
function generator(seedText) {
  let seed = 0x9e3779b9;
  for (const ch of seedText) seed = Math.imul(seed ^ ch.charCodeAt(0), 0x85ebca6b) >>> 0;
  return () => {
    seed = (seed + 0x6d2b79f5) >>> 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const EDGE = [
  0, 1, 2, 0x7f, 0x80, 0xff, 0x100, 0x7fff, 0x8000, 0xffff, 0x10000, 0x7fffffff, 0x80000000, 0xffffffff, 0xfffffffe,
];

class Cases {
  constructor(name) {
    this.random = generator(name);
  }
  int(n) {
    return Math.floor(this.random() * n);
  }
  pick(list) {
    return list[this.int(list.length)];
  }
  /** A 32-bit value: an edge value (one time in three), a mix of edge values, or random bits. */
  value() {
    const r = this.int(6);
    if (r < 2) return this.pick(EDGE) >>> 0;
    if (r === 2) return (this.pick(EDGE) ^ this.int(256)) >>> 0;
    if (r === 3) return (this.int(0x10000) * 0x10000 + this.int(0x10000)) >>> 0;
    if (r === 4) return (this.int(0x100) * 0x01010101) >>> 0;
    return (this.pick([0, 0xffffff00, 0xffff0000, 0x00ffff00]) | this.int(0x100)) >>> 0;
  }
  ccr() {
    return this.int(32);
  }
}

const hex = (value, digits = 8) => `$${(value >>> 0).toString(16).toUpperCase().padStart(digits, '0')}`;
const SIZES = ['B', 'W', 'L'];

/** The lines of one case: set data registers, CCR, run `body`, dump. */
function caseLines(c, { body, dregs = 4, memory = false, setA = true, ccr = c.ccr(), extra = [], note = '' }) {
  const lines = [`* ${note || body.join(' / ')}`];
  for (let r = 0; r < dregs; r++) lines.push(`    MOVE.L  #${hex(c.value())},D${r}`);
  if (memory) {
    for (let i = 0; i < 16; i += 4) lines.push(`    MOVE.L  #${hex(c.value())},SCR+${i}`);
  }
  if (setA) lines.push('    LEA     SCR,A0', '    LEA     SCR+8,A1');
  lines.push(...extra);
  lines.push(
    `    MOVE    #${hex(ccr, 2)},CCR`,
    '    JSR     DMP_CLRC',
    ...body.map((b) => `    ${b}`),
    '    JSR     DMP_REGS',
    '    JSR     DMP_CYC',
  );
  if (memory) lines.push('    LEA     SCR,A0', '    MOVEQ   #16,D0', '    JSR     DMP_MEM');
  return lines;
}

function program(name, item, cases, { switches = '' } = {}) {
  const head = [
    '*-----------------------------------------------------------------------------',
    `* @item ${item}`,
    ...(switches ? [`* @switches ${switches}`] : []),
    `* Generated by tests/conformance/sim/generate-instructions.mjs - do not edit.`,
    '*-----------------------------------------------------------------------------',
    '    ORG     $1000',
    'START:',
    '    JSR     DMP_OPEN',
  ];
  const tail = [
    '    JSR     DMP_CLOSE',
    '    SIMHALT',
    '    DS.W    0',
    'PAD DS.B    16                  ; room for MOVEM -(A1) below SCR',
    'SCR DS.B    32',
    'PCREL DC.L  $89ABCDEF,$01234567',
    "    INCLUDE '..\\dumplib.X68'",
    '    END     START',
  ];
  return { name: `${PREFIX}${name}`, text: [...head, ...cases.flat(), ...tail].map((l) => `${l}\r\n`).join('') };
}

