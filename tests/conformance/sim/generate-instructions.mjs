#!/usr/bin/env node
// Writes the generated programs of tests/conformance/sim/instructions/ (ARCHITECTURE.md 6.4, 6.9
// item 2: "covering every instruction group of sim-core §3.16"). Owner: T3.
//
//     node tests/conformance/sim/generate-instructions.mjs [--check]
//
// Each program tests one instruction group with cases drawn from a fixed-seed generator: random
// operands mixed with the edge values that decide flags ($00, $7F, $80, $FF, $7FFF, $8000, ...) and a
// random condition code register, X included. Per case the program sets the registers (and a
// 16-byte scratch area for memory operands), clears the cycle counter, executes the instruction,
// and writes the registers, the cycle count and, for memory forms, the scratch area to result.bin.
// No case raises an exception (divisors are not zero, addresses are even): the exception programs
// are written by hand (../exceptions).
//
// The generated files are committed: the Wine oracle runs them as they are, and the twins of T4
// pick up every .X68 under tests/. `--check` exits 1 when a committed file differs from what this
// script writes (instructions.test.mjs runs it).

