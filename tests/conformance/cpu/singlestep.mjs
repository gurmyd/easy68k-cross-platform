// The 68000 single-step suite against EASy68K's CPU core (ARCHITECTURE.md 6.1 L7, 6.2.4).
//
// Each test of SingleStepTests/680x0 (68000/v1) gives a complete CPU state before and after one
// instruction of a real 68000. This module turns a suite file into a simulator-twin script
// (tests/oracle/native-twin, README.md "Scripts") that loads each initial state into the
// simulator, executes the instruction with Trace Into, and dumps the registers and every memory
// byte the test names; and it reads the transcript back and compares it with the expected final
// state. The same script also runs through the native twins, which must give the same transcript.
//
// How a test is set up (the simulator keeps no other state that one instruction could observe):
//   - exceptions are enabled (Options > Enable Exceptions), as on a real 68000;
//   - first a NOP is traced at $000400 with SR = $2700, so that the double-fault latch and the
//     static result of the previous test cannot carry over (sim-core.md 3.4, 3.14);
//   - SR, USP, SSP, D0-D7, A0-A6 and PC are set as typed into the register boxes; the two
//     prefetch words are written at PC and PC+2 (the suite's PC is the address of the opcode) and
//     every RAM byte of the initial state is written;
//   - one Trace Into is executed.
// Cycle counts, prefetch contents after the instruction and bus transactions are not compared:
// EASy68K does not model them (docs/porting/ground-truth.md section 5).
//
// Part of easy68k-cross-platform, an unofficial port of EASy68K. GPL-2.0-or-later.

import { gunzipSync } from 'node:zlib';
import { readFileSync } from 'node:fs';

export const NEUTRAL_ADDRESS = 0x400;
const REGS = ['d0', 'd1', 'd2', 'd3', 'd4', 'd5', 'd6', 'd7', 'a0', 'a1', 'a2', 'a3', 'a4', 'a5', 'a6'];
const hex = (v, n) => (v >>> 0).toString(16).toUpperCase().padStart(n, '0');

/** @typedef {{ d0: number, d1: number, d2: number, d3: number, d4: number, d5: number, d6: number, d7: number,
 *   a0: number, a1: number, a2: number, a3: number, a4: number, a5: number, a6: number,
 *   usp: number, ssp: number, sr: number, pc: number, prefetch: number[], ram: [number, number][] }} CpuState */
/** @typedef {{ name: string, initial: CpuState, final: CpuState, length?: number }} SuiteTest */

/** @param {string} path a .json.gz file of the suite @returns {SuiteTest[]} */
export function readSuiteFile(path) {
  return JSON.parse(gunzipSync(readFileSync(path)).toString('utf8'));
}

/** Runs of consecutive addresses: [[start, bytes[]], ...], in address order. */
export function byteRuns(ram) {
  const sorted = [...ram].sort((a, b) => a[0] - b[0]);
  const runs = [];
  for (const [address, value] of sorted) {
    const last = runs[runs.length - 1];
    if (last && last[0] + last[1].length === address) last[1].push(value);
    else runs.push([address, [value]]);
  }
  return runs;
}

/** The final RAM addresses of a test, in the order the transcript's `bytes` line reports them. */
export function finalAddresses(test) {
  return test.final.ram.map(([address]) => address & 0xffffff);
}

/**
 * The script for a list of tests (one suite file).
 * @param {SuiteTest[]} tests
 * @returns {string}
 */
export function scriptFor(tests) {
  const out = ['# generated by tests/conformance/cpu/singlestep.mjs', 'option exceptions 1'];
  tests.forEach((test, index) => {
    const s = test.initial;
    out.push(
      `echo test ${index}`,
      'hostlog off',
      `poke $${hex(NEUTRAL_ADDRESS, 6)} 4E71`,
      'reg SR $2700',
      `reg PC $${hex(NEUTRAL_ADDRESS, 6)}`,
      'trace 1',
      'hostlog on',
      `reg SR $${hex(s.sr, 4)}`,
      `reg USP $${hex(s.usp, 8)}`,
      `reg SSP $${hex(s.ssp, 8)}`,
    );
    REGS.forEach((r) => out.push(`reg ${r.toUpperCase()} $${hex(s[r], 8)}`));
    out.push(`reg PC $${hex(s.pc, 8)}`);
    out.push(`poke $${hex(s.pc, 8)} ${hex(s.prefetch[0], 4)}${hex(s.prefetch[1], 4)}`);
    for (const [address, bytes] of byteRuns(s.ram))
      out.push(`poke $${hex(address, 8)} ${bytes.map((b) => hex(b, 2)).join('')}`);
    out.push('trace 1', 'dump regs');
    const addresses = finalAddresses(test);
    // `bytes` lines of at most 64 addresses, so that script lines stay short
    for (let i = 0; i < addresses.length || i === 0; i += 64) {
      out.push(['dump bytes', ...addresses.slice(i, i + 64).map((a) => `$${hex(a, 6)}`)].join(' '));
    }
  });
  return out.join('\n') + '\n';
}

/**
 * What the simulator did for each test, read from a transcript of scriptFor().
 * @param {string} transcript
 * @returns {{ regs: Record<string, number>, bytes: number[], messages: string[], alerts: number, status: number }[]}
 */
export function parseTranscript(transcript) {
  const results = [];
  let current = null;
  for (const line of transcript.split('\n')) {
    if (line.startsWith('echo test ')) {
      current = { regs: {}, bytes: [], messages: [], alerts: 0, status: NaN };
      results.push(current);
    } else if (!current) {
      continue;
    } else if (line.startsWith('regs ')) {
      for (const field of line.slice(5).split(' ')) {
        const [name, value] = field.split('=');
        current.regs[name] = name === 'cycles' ? Number(value) : parseInt(value, 16);
      }
    } else if (line.startsWith('bytes ')) {
      const h = line.slice(6);
      for (let i = 0; i < h.length; i += 2) current.bytes.push(parseInt(h.slice(i, i + 2), 16));
    } else if (line.startsWith('@message ')) {
      current.messages.push(line.slice(9));
    } else if (line === 'wait alert') {
      current.alerts++;
    } else if (line.startsWith('status ')) {
      current.status = Number(line.split(' ')[1]);
    }
  }
  return results;
}

const SR_BITS = [
  ['C', 0x0001],
  ['V', 0x0002],
  ['Z', 0x0004],
  ['N', 0x0008],
  ['X', 0x0010],
  ['IPL', 0x0700],
  ['S', 0x2000],
  ['T', 0x8000],
];

/** The trace line EASy68K adds for every traced instruction ("PC=...  Code=...  NAME"). */
const isTraceLine = (message) => /^"PC=[0-9A-F]{8} {2}Code=[0-9A-F]{4} {2}/.test(message);

/**
 * Compare one result with the test's expected final state.
 * @param {SuiteTest} test
 * @param {ReturnType<typeof parseTranscript>[number]} result
 * @returns {string[]} the differing fields, e.g. ["SR.V", "D3"]; empty when the result matches
 */
export function differences(test, result) {
  const f = test.final;
  const r = result.regs;
  const diff = [];
  for (const name of REGS) if (r[name.toUpperCase()] >>> 0 !== f[name] >>> 0) diff.push(name.toUpperCase());
  if (r.USP >>> 0 !== f.usp >>> 0) diff.push('USP');
  if (r.SSP >>> 0 !== f.ssp >>> 0) diff.push('SSP');
  if (r.PC >>> 0 !== f.pc >>> 0) diff.push('PC');
  const srDelta = (r.SR ^ f.sr) & 0xffff;
  for (const [name, mask] of SR_BITS) if (srDelta & mask) diff.push(`SR.${name}`);
  if (srDelta & ~SR_BITS.reduce((a, [, m]) => a | m, 0)) diff.push('SR.unused');
  const expected = f.ram.map(([, value]) => value);
  if (result.bytes.length !== expected.length || result.bytes.some((b, i) => b !== expected[i])) diff.push('RAM');
  const extra = result.messages.filter((m) => !isTraceLine(m));
  if (extra.length || result.alerts) diff.push('message');
  return diff;
}

const VECTOR_NAMES = {
  2: 'bus error',
  3: 'address error',
  4: 'illegal instruction',
  5: 'zero divide',
  6: 'CHK',
  7: 'TRAPV',
  8: 'privilege violation',
  9: 'trace',
  10: 'line 1010',
  11: 'line 1111',
};

/**
 * The exception a real 68000 takes in this test, or null: the vector whose long word (given in
 * the initial RAM) the final PC equals. TRAP #0-#15 are reported as "TRAP".
 * @param {SuiteTest} test
 * @returns {string|null}
 */
export function expectedException(test) {
  const ram = new Map(test.initial.ram.map(([address, value]) => [address & 0xffffff, value]));
  const pc = test.final.pc >>> 0;
  for (let vector = 2; vector < 48; vector++) {
    if (vector > 11 && vector < 32) continue;
    const at = vector * 4;
    if (![0, 1, 2, 3].every((k) => ram.has(at + k))) continue;
    const value = ((ram.get(at) << 24) | (ram.get(at + 1) << 16) | (ram.get(at + 2) << 8) | ram.get(at + 3)) >>> 0;
    if (value === pc) return vector >= 32 ? 'TRAP' : VECTOR_NAMES[vector];
  }
  return null;
}

/**
 * The class of a deviation: the instruction family (from the suite file name), the exception a
 * real 68000 takes (if any) and the differing fields. Registers are grouped (any of D0-D7 -> Dn,
 * A0-A6 -> An) so that the class does not depend on which register a random test happened to use.
 * @param {string} fileName e.g. "DIVS.json.gz"
 * @param {string[]} diff
 * @param {string|null} [exception] expectedException(test)
 */
export function deviationClass(fileName, diff, exception = null) {
  const family = fileName.replace(/\.json\.gz$/, '');
  const group = (d) => (/^D\d$/.test(d) ? 'Dn' : /^A\d$/.test(d) ? 'An' : /^SR\.[XNZVC]$/.test(d) ? 'CCR' : d);
  const fields = [...new Set(diff.map(group))].sort();
  return `${family}${exception ? ` [${exception}]` : ''}: ${fields.join(' ')}`;
}
