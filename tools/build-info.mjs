#!/usr/bin/env node
// Writes app/src/build-info.ts: the port's version, the commit and the build
// date (ARCHITECTURE.md 7.5), and the repository address (10.2, O-14: read
// from the Git remote at build time, nothing hard-coded).
//
//     node tools/build-info.mjs
//
// The file is generated and git-ignored. The Vite configuration calls
// writeBuildInfo() on every dev-server start and build, and `npm run typecheck`
// calls this script first, so the file always exists when it is needed.
//
// Sources, first match wins:
//   version     the root package.json
//   commit      GITHUB_SHA, else `git rev-parse HEAD`, else "unknown"
//   repository  GITHUB_REPOSITORY ("owner/name"), else the "origin" remote of
//               the Git checkout if it is a github.com address, else null
//   date        SOURCE_DATE_EPOCH (seconds), else the current time (UTC)

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const buildInfoPath = join(repo, 'app', 'src', 'build-info.ts');

function git(args) {
  try {
    return execFileSync('git', args, { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

/** "owner/name" from a github.com remote URL, or null. */
export function repositoryFromRemote(url) {
  const match = /github\.com[:/]([^/\s]+)\/([^/\s]+?)(?:\.git)?\/?$/i.exec(url.trim());
  return match ? `${match[1]}/${match[2]}` : null;
}

/** @returns {{ version: string, commit: string, date: string, repository: string | null }} */
export function collectBuildInfo() {
  const { version } = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8'));
  const commit = process.env.GITHUB_SHA || git(['rev-parse', 'HEAD']) || 'unknown';
  const repository = process.env.GITHUB_REPOSITORY || repositoryFromRemote(git(['remote', 'get-url', 'origin']));
  const epoch = Number(process.env.SOURCE_DATE_EPOCH);
  const date = new Date(Number.isFinite(epoch) && epoch > 0 ? epoch * 1000 : Date.now()).toISOString();
  return { version, commit, date, repository: repository || null };
}

export function renderBuildInfo(info) {
  return [
    '// Generated by tools/build-info.mjs. Do not edit; the file is not committed.',
    '',
    'export interface BuildInfo {',
    '  /** Semantic version of the port (root package.json). */',
    '  readonly version: string;',
    '  /** Full commit hash, or "unknown" outside a Git checkout. */',
    '  readonly commit: string;',
    '  /** Build time, ISO 8601 UTC. */',
    '  readonly date: string;',
    '  /** GitHub repository as "owner/name", or null when it is not known. */',
    '  readonly repository: string | null;',
    '}',
    '',
    `export const buildInfo: BuildInfo = ${JSON.stringify(info, null, 2)};`,
    '',
  ].join('\n');
}

/** Writes the file if its content changed; returns the information written. */
export function writeBuildInfo(overrides = {}) {
  const info = { ...collectBuildInfo(), ...overrides };
  const text = renderBuildInfo(info);
  if (!existsSync(buildInfoPath) || readFileSync(buildInfoPath, 'utf8') !== text) {
    writeFileSync(buildInfoPath, text);
  }
  return info;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (invokedDirectly) {
  const info = writeBuildInfo();
  console.log(
    `build-info: ${info.version} ${info.commit.slice(0, 12)} ${info.date} ${info.repository ?? '(no repository)'}`,
  );
}
