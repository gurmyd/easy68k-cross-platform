#!/usr/bin/env node
// `npm run typecheck`: `tsc --noEmit` for every workspace (ARCHITECTURE.md 7.2).
//
//     node tools/typecheck.mjs
//
// Generates app/src/build-info.ts first (tools/build-info.mjs).
//
// `desktop/` has no TypeScript source until DV2 writes `desktop/src/`, and
// `tsc -p desktop/tsconfig.json` would then fail with TS18003 "No inputs were
// found". Until that file exists, the desktop settings are checked with a
// probe instead: a small main-process file (Electron, Node and serialport
// imports, __dirname) compiled with desktop/tsconfig.json from
// build/typecheck-probe/desktop/, next to a package.json with the same "type"
// as desktop/package.json, so that `module: nodenext` picks the same module
// format as it will for desktop/src. The probe must type-check and must
// compile to CommonJS, which is what Electron's main process and sandboxed
// preload scripts load. Once desktop/src has a .ts file, the real project is
// checked and the probe is not used.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeBuildInfo } from './build-info.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tsc = createRequire(join(repo, 'package.json')).resolve('typescript/bin/tsc');

/** Workspace, the folders whose .ts/.tsx files make up its sources, and what to do without any. */
const PROJECTS = [
  { name: 'app', sourceDirs: ['src', '.'] },
  { name: 'desktop', sourceDirs: ['src'], withoutSources: probeDesktop },
  { name: 'tests', sourceDirs: ['.'] },
];

function hasTypeScript(dir) {
  if (!existsSync(dir)) return false;
  for (const entry of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    if (/[\\/]node_modules([\\/]|$)/.test(entry.parentPath)) continue;
    if (/\.tsx?$/.test(entry.name)) return true;
  }
  return false;
}

function runTsc(args) {
  return spawnSync(process.execPath, [tsc, ...args], { stdio: 'inherit' }).status === 0;
}

const PROBE = `// Generated by tools/typecheck.mjs: checks desktop/tsconfig.json until desktop/src exists.
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { app, BrowserWindow, ipcMain, protocol } from 'electron';
import { SerialPort } from 'serialport';

protocol.registerSchemesAsPrivileged([{ scheme: 'app', privileges: { standard: true, secure: true } }]);

export async function start(): Promise<number> {
  await app.whenReady();
  const window = new BrowserWindow({
    webPreferences: { contextIsolation: true, sandbox: true, preload: join(__dirname, 'preload.js') },
  });
  ipcMain.handle('read', async (_event, path: string) => readFile(path));
  await window.loadURL(process.env['EASY68K_DEV_SERVER_URL'] ?? 'app://easy68k/index.html');
  return (await SerialPort.list()).length;
}
`;

/** Checks desktop/tsconfig.json with a probe file; true when it passes. */
function probeDesktop() {
  const dir = join(repo, 'build', 'typecheck-probe', 'desktop');
  const out = join(dir, 'out');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const { type = 'commonjs' } = JSON.parse(readFileSync(join(repo, 'desktop', 'package.json'), 'utf8'));
  writeFileSync(join(dir, 'package.json'), `${JSON.stringify({ private: true, type }, null, 2)}\n`);
  writeFileSync(join(dir, 'probe.ts'), PROBE);
  const extendsPath = relative(dir, join(repo, 'desktop', 'tsconfig.json'))
    .split('\\')
    .join('/');
  writeFileSync(
    join(dir, 'tsconfig.json'),
    `${JSON.stringify(
      { extends: extendsPath, compilerOptions: { rootDir: '.', outDir: './out' }, include: [], files: ['probe.ts'] },
      null,
      2,
    )}\n`,
  );
  const project = join(dir, 'tsconfig.json');
  console.log('typecheck desktop: no desktop/src yet - checking desktop/tsconfig.json with a probe file');
  if (!runTsc(['-p', project, '--noEmit'])) return false;
  if (!runTsc(['-p', project, '--noEmit', 'false'])) return false;
  const emitted = readFileSync(join(out, 'probe.js'), 'utf8');
  if (!/\brequire\("electron"\)/.test(emitted)) {
    console.error('typecheck desktop: the probe did not compile to CommonJS (no require("electron") in the output)');
    return false;
  }
  return true;
}

writeBuildInfo();

let failed = false;
for (const { name, sourceDirs, withoutSources } of PROJECTS) {
  const root = join(repo, name);
  let ok;
  if (sourceDirs.some((dir) => hasTypeScript(join(root, dir)))) {
    ok = runTsc(['-p', join(root, 'tsconfig.json'), '--noEmit']);
  } else if (withoutSources) {
    ok = withoutSources();
  } else {
    console.error(`typecheck ${name}: no TypeScript sources found`);
    ok = false;
  }
  if (ok) {
    console.log(`typecheck ${name}: ok`);
  } else {
    console.error(`typecheck ${name}: FAILED`);
    failed = true;
  }
}
process.exit(failed ? 1 : 0);
