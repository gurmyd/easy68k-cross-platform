#!/usr/bin/env node
// Produces test/expected.mjs: the outputs of every test case (test/cases.mjs)
// as the NATIVE patched twin (MSVC build of the same sources) produces them.
//
//     node engine/asm/test/tools/snapshot.mjs
//
// Review the diff of expected.mjs against docs/porting/assembler.md before
// committing it: the snapshot is only as good as that review.
//
// Part of easy68k-mac, an unofficial port of EASy68K. GPL-2.0-or-later.

import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CASES } from '../cases.mjs';
import { expandCases, nativeExe, repo, runNative, summarize } from './native-run.mjs';

if (!existsSync(nativeExe('patched'))) {
  console.error(`${nativeExe('patched')} not found: run node engine/asm/native/build.mjs first`);
  process.exit(1);
}
const out = {};
for (const run of expandCases(CASES)) {
  const r = runNative('patched', run, join(repo, 'build', 'asm-snapshot', 'run'));
  if (r.exitCode !== 0) throw new Error(`${run.key}: native twin exit code ${r.exitCode}`);
  out[run.key] = summarize(r);
}
const text = [
  '// GENERATED by test/tools/snapshot.mjs from the native patched twin; reviewed against',
  '// docs/porting/assembler.md. Do not edit by hand: change the case, rerun, review the diff.',
  '// Per run: listing (all lines, CR LF removed), s68 (records), msgs ([line, code, text, file]),',
  '// errors, warnings.',
  '',
  `export const EXPECTED = ${JSON.stringify(out, null, 1)};`,
  '',
].join('\n');
writeFileSync(join(repo, 'engine', 'asm', 'test', 'expected.mjs'), text);
console.log(`${Object.keys(out).length} runs written to engine/asm/test/expected.mjs`);
